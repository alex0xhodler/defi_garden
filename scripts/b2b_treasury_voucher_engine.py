# Core Canonical Mathematical Constants (mirrored from trust-rails.js & PRD-002)
CONSERVATIVE_NET_APY = 0.0510      # 5.10% conservative Base net APY (Aave V3 / Morpho Blue)
TAX_HEADROOM_MULTIPLIER = 1.20    # +20% buffer for US state sales tax / EU VAT slippage
SAFETY_BUFFER_MULTIPLIER = 1.25   # 1.25x over-collateralization against floating APY decay
DEFAULT_BASE_URL = "https://www.defi.garden/plan.html"


def calculate_financial_proof(monthly_saas_usd: float, custom_apy: Optional[float] = None) -> Dict[str, Any]:
    """
    Computes mathematical financial proofs for a given monthly SaaS liability.
    """
    net_apy = custom_apy if custom_apy is not None else CONSERVATIVE_NET_APY
    
    # Step 1: Base annual liability
    annual_raw_liability = monthly_saas_usd * 12.0
    
    # Step 2: Tax-buffered liability
    monthly_effective_liability = monthly_saas_usd * TAX_HEADROOM_MULTIPLIER
    annual_tax_adjusted_liability = annual_raw_liability * TAX_HEADROOM_MULTIPLIER
    
    # Step 3: Unbuffered theoretical capital requirement
    unbuffered_capital = annual_tax_adjusted_liability / net_apy
    
    # Step 4: Hardened Treasury Allocation (with 1.25x Safety Buffer)
    required_treasury_deposit = round(unbuffered_capital * SAFETY_BUFFER_MULTIPLIER)
    
    # Step 5: Monthly and Annual Gross Yield generated by the allocated deposit
    annual_gross_yield = required_treasury_deposit * net_apy
    monthly_gross_yield = annual_gross_yield / 12.0
    
    # Step 6: Surplus Sponge allocation (excess yield diverted to 3-month escrow reserve)
    monthly_surplus = monthly_gross_yield - monthly_effective_liability
    annual_surplus = monthly_surplus * 12.0
    
    # Step 7: 5-Year Cumulative P&L Cashflow Savings
    five_year_savings = annual_raw_liability * 5.0
    
    return {
        "monthly_saas_raw_usd": round(monthly_saas_usd, 2),
        "annual_saas_raw_usd": round(annual_raw_liability, 2),
        "tax_headroom_multiplier": TAX_HEADROOM_MULTIPLIER,
        "monthly_tax_adjusted_usd": round(monthly_effective_liability, 2),
        "annual_tax_adjusted_usd": round(annual_tax_adjusted_liability, 2),
        "conservative_net_apy_pct": round(net_apy * 100.0, 2),
        "safety_buffer_multiplier": SAFETY_BUFFER_MULTIPLIER,
        "required_treasury_deposit_usdc": required_treasury_deposit,
        "monthly_gross_yield_usd": round(monthly_gross_yield, 2),
        "annual_gross_yield_usd": round(annual_gross_yield, 2),
        "monthly_surplus_escrow_usd": round(monthly_surplus, 2),
        "annual_surplus_escrow_usd": round(annual_surplus, 2),
        "five_year_cumulative_savings_usd": round(five_year_savings, 2),
        "principal_retained_pct": 100.0,
        "bank_out_of_pocket_usd": 0.0
    }


def generate_voucher_url(
    company_name: str,
    monthly_saas_usd: float,
    saas_stack: str = "Slack + Notion + GitHub + AWS",
    ref_tag: str = "b2b_outbound_q3",
    custom_apy: Optional[float] = None
) -> str:
    """
    Constructs the dynamic, pre-solved DeFi Garden intent voucher URL.
    """
    proof = calculate_financial_proof(monthly_saas_usd, custom_apy)
    
    params = {
        "company": company_name,
        "bill": str(int(round(monthly_saas_usd))),
        "capital": str(proof["required_treasury_deposit_usdc"]),
        "preset": "treasury_shield",
        "stack": saas_stack,
        "chain": "base",
        "token": "USDC",
        "ref": ref_tag
    }
    
    return f"{DEFAULT_BASE_URL}?{urllib.parse.urlencode(params)}"


