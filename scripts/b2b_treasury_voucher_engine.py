def qualify_account(
    company_name: str,
    treasury_stablecoins_usd: float,
    team_size: int,
    estimated_monthly_burn: float,
    multisig_type: str = "Safe",
    primary_chain: str = "Base"
) -> Dict[str, Any]:
    """
    Scores an inbound or outbound lead against the Stage 2 TREASURY-FIT Framework.
    """
    score = 0
    reasons = []
    disqualified = False
    disqualify_reason = None
    
    # Gate 1: Liquidity Check
    if treasury_stablecoins_usd < 100000:
        disqualified = True
        disqualify_reason = f"Treasury stablecoins (${treasury_stablecoins_usd:,.0f}) below $100K minimum threshold."
    elif treasury_stablecoins_usd >= 1000000:
        score += 40
        reasons.append("High Liquidity (>=$1M stablecoins): +40 pts")
    elif treasury_stablecoins_usd >= 300000:
        score += 30
        reasons.append("Solid Liquidity ($300k-$1M stablecoins): +30 pts")
    else:
        score += 20
        reasons.append("Sufficient Liquidity ($100k-$300k stablecoins): +20 pts")
        
    # Gate 2: Team Size & SaaS Burn
    if team_size >= 10:
        score += 25
        reasons.append(f"Optimal Team Size ({team_size} members, ${estimated_monthly_burn:,.0f}/mo burn): +25 pts")
    elif team_size >= 4:
        score += 20
        reasons.append(f"Viable Team Size ({team_size} members, ${estimated_monthly_burn:,.0f}/mo burn): +20 pts")
    else:
        score += 10
        reasons.append(f"Small Pod ({team_size} members): +10 pts")
        
    # Gate 3: Multisig / Safe Infrastructure
    if "safe" in multisig_type.lower() or "gnosis" in multisig_type.lower():
        score += 20
        reasons.append("Safe Multisig Native: +20 pts")
    else:
        score += 10
        reasons.append(f"Alternative Wallet Setup ({multisig_type}): +10 pts")
        
    # Gate 4: Chain Ecosystem Alignment
    if primary_chain.lower() in ["base", "optimism", "arbitrum", "ethereum"]:
        score += 15
        reasons.append(f"EVM/L2 Native ({primary_chain}): +15 pts")
    else:
        score += 5
        reasons.append(f"Non-EVM / Alt L1 ({primary_chain}): +5 pts")
        
    # Determine Tier
    if disqualified:
        tier = "DISQUALIFIED"
        action = "Archive / Nurture on low-priority newsletter."
    elif score >= 80:
        tier = "TIER_1_IMMEDIATE_PILOT"
        action = "Direct multi-channel outbound sprint (CEO + CFO + Ops). Target close within 7 days."
    elif score >= 60:
        tier = "TIER_2_FAST_TRACK"
        action = "Standard outbound sequence (Touch 1-4). Target close within 14 days."
    else:
        tier = "TIER_3_INCUBATION"
        action = "Add to self-serve waitlist and community education loop."
        
    return {
        "company": company_name,
        "score": score if not disqualified else 0,
        "tier": tier,
        "disqualified": disqualified,
        "disqualify_reason": disqualify_reason,
        "recommended_action": action,
        "score_breakdown": reasons
    }


